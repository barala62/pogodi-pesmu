function normalizeStr(text) {
  return text
    .toLowerCase()
    .replace(/[čć]/g, 'c')
    .replace(/đ/g, 'dj')
    .replace(/š/g, 's')
    .replace(/ž/g, 'z')
    .replace(/[^a-z0-9\s]/g, '')
    .trim();
}

function makeSearchTerms(title, artist) {
  const normTitle = normalizeStr(title);
  const normArtist = normalizeStr(artist);
  const terms = new Set();
  terms.add(normTitle);
  terms.add(normArtist);
  terms.add(`${normArtist} ${normTitle}`);
  terms.add(`${normTitle} ${normArtist}`);

  // Add individual words if meaningful
  normTitle.split(/\s+/).forEach(w => { if (w.length > 2) terms.add(w); });
  normArtist.split(/\s+/).forEach(w => { if (w.length > 2) terms.add(w); });

  return Array.from(terms);
}

