function generateFile(category, prefix, items, outPath) {
  const songs = items.map((item, i) => {
    const searchTerms = makeSearchTerms(item.title, item.artist);
    return {
      id: `${prefix}-exp-${i + 1}`,
      title: item.title,
      artist: item.artist,
      year: item.year,
      genre: category,
      searchTerms: searchTerms,
      previewQuery: `${item.artist} ${item.title}`
    };
  });

  const content = `import { Song } from '../../types';\n\nexport const EXPANDED_${prefix.toUpperCase()}_SONGS: Song[] = ${JSON.stringify(songs, null, 2)};\n`;
  fs.writeFileSync(outPath, content, 'utf8');
  console.log(`Generated ${songs.length} songs for ${prefix} at ${outPath}`);
}

